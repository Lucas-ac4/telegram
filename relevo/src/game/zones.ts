import type { PowerId } from './powers';

/**
 * Mundos: a medida que la cadena crece, el escenario cambia, la dificultad sube y
 * aparecen mecánicas nuevas, pero también beneficios (trampolines, cohetes, monedas...),
 * como al subir de altura en Sky Jump. Cada mundo se presenta con un cartel y,
 * la primera vez que se llega, da una recompensa de exploración en la pestaña Mundos.
 */

export type DecorKind =
  | 'fern'
  | 'bells'
  | 'lotus'
  | 'cloud'
  | 'crystal'
  | 'rock'
  | 'mushroom'
  | 'paperLantern'
  | 'coral'
  | 'cactus'
  | 'bamboo';
export type Weather = 'rain' | 'snow' | 'petals' | 'embers' | 'bubbles' | 'sparkles' | 'leaves' | 'spirits' | null;

export interface ZonePalette {
  sky: [string, string, string, string];
  stars: number;
  /** Radio de la luna en unidades (0 = sin luna). */
  moon: number;
  /** Luna llena en vez de creciente. */
  fullMoon: boolean;
  bridge: string | null;
  falls: number;
  clouds: string | null;
  aurora: boolean;
  mountains: string | null;
  /** Colinas o dunas redondeadas. */
  hills: string | null;
  planets: boolean;
  /** Banda de la Vía Láctea. */
  galaxy: boolean;
  /** Sol radiante (último mundo). */
  sun: boolean;
  /** Ciudad con ventanas encendidas. */
  city: boolean;
  /** Resplandor en el horizonte (lava, ciudad...). */
  glow: string | null;
  /** Arcoíris lejano. */
  rainbow: boolean;
  /** Eclipse: disco oscuro con corona de luz. */
  eclipse: boolean;
  /** Pirámides en el horizonte (color). */
  pyramids: string | null;
  /** Torres o agujas (castillo, hielo, pagodas) en el horizonte (color). */
  spires: string | null;
  trees: string | null;
  water: [string, string] | null;
  mist: string;
  lights: string;
  weather: Weather;
  lightning: boolean;
  /** Niebla sobre las hojas: sólo las semillas de luz brillan a través. */
  fog: boolean;
}

/** Reglas de cada mundo: cuánto de cada mecánica y qué beneficio aparece más. */
export interface ZoneRules {
  dryMul: number;
  fragile: number;
  moving: number;
  /** Velocidad del aro móvil (1 = normal). */
  moveSpeed: number;
  double: number;
  waveMul: number;
  fuseMul: number;
  ringMul: number;
  speedMul: number;
  goldMul: number;
  /** Multiplica la chance de que aparezca un potenciador. */
  powerMul: number;
  /** Beneficio estrella del mundo (aparece 3 veces más). */
  favor: PowerId | null;
}

export interface Zone {
  id: string;
  name: string;
  at: number;
  /** Qué hay de nuevo (cartel al entrar y tarjeta del mapa). */
  intro: string;
  /** Monedas por llegar la primera vez. */
  reward: number;
  palette: ZonePalette;
  rules: ZoneRules;
  decor: DecorKind[];
  firefly: string;
  /** Degradado para la tarjeta del mapa (CSS). */
  card: string;
}

